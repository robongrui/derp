"""The kick's leg frames (platform/kick_frames_stock.h) from their PNGs.

Usage: py -I scripts/make_kick_frames.py output/kick-sprites [doom.wad]

Reads the front kick (8-bit paletted PNGs in PLAYPAL's order, with
sprite-offsets-v5.json beside them) and writes each frame as palette indices in runs: a
count of transparent pixels, a count of painted ones, then those indices, row by row.
With a WAD given, the PNGs' palette is checked against its PLAYPAL.
"""
import json, os, struct, sys, zlib

SETS = (("front-kick-v4", "front", "CD"),)


def read_png(path):
    data = open(path, "rb").read()
    at, chunks, packed = 8, {}, b""
    while at < len(data):
        size, kind = struct.unpack(">I4s", data[at:at + 8])
        body = data[at + 8:at + 8 + size]
        if kind == b"IDAT":
            packed += body
        else:
            chunks[kind] = body
        at += 12 + size
    w, h, depth, colour, _, _, lace = struct.unpack(">IIBBBBB", chunks[b"IHDR"])
    if depth != 8 or colour != 3 or lace:
        sys.exit(path + ": not an 8-bit paletted PNG")
    raw, rows, before = zlib.decompress(packed), [], bytes(w)
    for y in range(h):
        kind, line = raw[y * (w + 1)], bytearray(raw[y * (w + 1) + 1:(y + 1) * (w + 1)])
        for x in range(w):
            a, b, c = (line[x - 1] if x else 0), before[x], (before[x - 1] if x else 0)
            if kind == 1:
                line[x] = (line[x] + a) & 255
            elif kind == 2:
                line[x] = (line[x] + b) & 255
            elif kind == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(bytes(line))
        before = line
    alpha = chunks.get(b"tRNS", b"")
    alpha += b"\xff" * (256 - len(alpha))
    return w, h, rows, chunks[b"PLTE"], alpha


def playpal(path):
    data = open(path, "rb").read()
    count, table = struct.unpack("<II", data[4:12])
    for i in range(count):
        place, size, name = struct.unpack("<II8s", data[table + 16 * i:table + 16 * i + 16])
        if name.rstrip(b"\0") == b"PLAYPAL":
            return data[place:place + 768]
    sys.exit(path + ": no PLAYPAL")


def runs(w, h, rows, alpha):
    out, clear, pixels = [], 0, []
    flat = [(index if alpha[index] >= 128 else -1) for row in rows for index in row]
    at = 0
    while at < len(flat):
        clear = 0
        while at < len(flat) and flat[at] < 0 and clear < 255:
            clear, at = clear + 1, at + 1
        pixels = []
        while at < len(flat) and flat[at] >= 0 and len(pixels) < 255:
            pixels.append(flat[at])
            at += 1
        out += [clear, len(pixels)] + pixels
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    folder = sys.argv[1]
    offsets = json.load(open(os.path.join(folder, "sprite-offsets-v5.json")))
    wad = playpal(sys.argv[2]) if len(sys.argv) > 2 else None
    text = ["/* The kick's leg (p_kick.c, scene3d/kick_view.cpp): generated by scripts/make_kick_frames.py from",
            "   output/kick-sprites. Stand-in art, AI-generated with ChatGPT (THIRD_PARTY.md). Each frame: its size, its patch offsets as a weapon",
            "   frame's (left, top), and its palette indices in runs: transparent count, painted count,",
            "   that many indices, row by row. */",
            "#ifndef DOOM_KICK_FRAMES_STOCK_H", "#define DOOM_KICK_FRAMES_STOCK_H", ""]
    table = []
    for folder_name, name, frames in SETS:
        for frame in frames:
            w, h, rows, palette, alpha = read_png(os.path.join(folder, folder_name, frame + ".png"))
            if wad and palette != wad:
                sys.exit(folder_name + "/" + frame + ": its palette is not the WAD's PLAYPAL")
            left, top = offsets[folder_name][frame]["doom_patch_left_top"]
            data = runs(w, h, rows, alpha)
            label = "doom_kick_%s_%s" % (name, frame.lower())
            text.append("static const unsigned char %s[] = {" % label)
            for i in range(0, len(data), 40):
                text.append("    " + ",".join(str(v) for v in data[i:i + 40]) + ",")
            text.append("};")
            table.append("    { %s, sizeof %s, %d, %d, %d, %d },   /* %s %s */" % (label, label, w, h, left, top, name, frame))
    text += ["", "struct doom_kick_frame { const unsigned char *runs; unsigned size; int width, height, left, top; };",
             "/* Front kick: C, D. */",
             "static const doom_kick_frame doom_kick_frames[] = {"] + table + ["};", "", "#endif", ""]
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "platform", "kick_frames_stock.h")
    open(out, "w", newline="\n").write("\n".join(text))
    print(out, len(table), "frames")


main()
