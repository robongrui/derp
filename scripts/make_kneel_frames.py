"""The kneeling soldiers' frames (platform/kneel_frames_stock.h) from their sheets.

Usage: py -I scripts/make_kneel_frames.py output/kneeling-native path/to/doom.wad

Reads kneel-aim.png, kneel-fire.png and kneel-pain.png: RGBA, 1024x1024, every art pixel a 4x4 block,
4x4 cells of 64x64 art pixels (rows: zombieman views 1-4, 5-8, shotgun guy views 1-4, 5-8), each figure's
lowest pixel on row 60 and its origin on column 32, colours exactly PLAYPAL's. Each cell is cut to what is
drawn and written as palette indices in runs, as kick_frames_stock.h: a count of transparent pixels, a
count of painted ones, then those indices, row by row. The table also keeps a hash of each soldier's own
aim frame as id drew it (POSSE1, SPOSE1), so replaced art (a PWAD) keeps the squashed legs.
"""
import os, struct, sys, zlib

SPRITES = ("POSS", "SPOS")
SHEETS = ("aim", "fire", "pain")
CELL, SCALE, FEET, MIDDLE = 64, 4, 60, 32


def read_png(path):
    """RGBA rows of an 8-bit RGB or RGBA PNG."""
    data = open(path, "rb").read()
    at, chunks, packed = 8, {}, b""
    while at < len(data):
        size, kind = struct.unpack(">I4s", data[at:at + 8])
        body = data[at + 8:at + 8 + size]
        if kind == b"IDAT":
            packed += body
        else:
            chunks[kind] = body
        at += 12 + size
    w, h, depth, colour, _, _, lace = struct.unpack(">IIBBBBB", chunks[b"IHDR"])
    if depth != 8 or colour not in (2, 6) or lace:
        sys.exit(path + ": not an 8-bit RGB(A) PNG")
    bpp = 4 if colour == 6 else 3
    stride = w * bpp
    raw, rows, before = zlib.decompress(packed), [], bytes(stride)
    for y in range(h):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b = before[x]
            c = before[x - bpp] if x >= bpp else 0
            if kind == 1:
                line[x] = (line[x] + a) & 255
            elif kind == 2:
                line[x] = (line[x] + b) & 255
            elif kind == 3:
                line[x] = (line[x] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append([tuple(line[x * bpp:x * bpp + 3]) + ((line[x * bpp + 3],) if bpp == 4 else (255,)) for x in range(w)])
        before = line
    return w, h, rows


def lumps(path):
    data = open(path, "rb").read()
    count, table = struct.unpack("<II", data[4:12])
    out = {}
    for i in range(count):
        place, size, name = struct.unpack("<II8s", data[table + 16 * i:table + 16 * i + 16])
        out.setdefault(name.rstrip(b"\0").decode("ascii", "replace").upper(), data[place:place + size])
    return out


def patch_hash(raw):
    """FNV-1a over a patch decoded as (index, coverage) pairs, transparent as two zeros (death_rigs_stock.h)."""
    w, h = struct.unpack_from("<hh", raw, 0)
    pairs = bytearray(w * h * 2)
    for x in range(w):
        pos = struct.unpack_from("<i", raw, 8 + 4 * x)[0]
        while raw[pos] != 255:
            top, length = raw[pos], raw[pos + 1]
            for k in range(length):
                if top + k < h:
                    i = ((top + k) * w + x) * 2
                    pairs[i], pairs[i + 1] = raw[pos + 3 + k], 255
            pos += length + 4
    value = 2166136261
    for b in pairs:
        value = ((value ^ b) * 16777619) & 0xFFFFFFFF
    return w, h, value


def runs(cells):
    out, at = [], 0
    while at < len(cells):
        clear = 0
        while at < len(cells) and cells[at] < 0 and clear < 255:
            clear, at = clear + 1, at + 1
        painted = []
        while at < len(cells) and cells[at] >= 0 and len(painted) < 255:
            painted.append(cells[at])
            at += 1
        out += [clear, len(painted)] + painted
    return out


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    folder, wad = sys.argv[1], lumps(sys.argv[2])
    palette = wad["PLAYPAL"][:768]
    index = {}
    for i in range(255, -1, -1):   # the first entry of a repeated colour
        index[tuple(palette[3 * i:3 * i + 3])] = i
    text = ["/* The DERP soldiers down on one knee (p_lanes.c's P_TacKneel, scene3d/kneel_view.cpp): generated by",
            "   scripts/make_kneel_frames.py from output/kneeling-native. Stand-in art, AI-generated with ChatGPT after id Software's zombieman and shotgun guy",
            "   (THIRD_PARTY.md). Per soldier (zombieman,",
            "   shotgun guy), per frame (aim, fire, pain) and view (Doom's rotations 1-8, each drawn, none mirrored):",
            "   its size, its patch offsets (left, top: the origin at its feet) and its palette indices in runs:",
            "   transparent count, painted count, that many indices, row by row. Used only where the soldier's own",
            "   aim frame (E1) is id's: its size and an FNV-1a hash of its decoded index and coverage pairs. */",
            "#ifndef DOOM_KNEEL_FRAMES_STOCK_H", "#define DOOM_KNEEL_FRAMES_STOCK_H", ""]
    table = {}
    for sheet in SHEETS:
        w, h, rows = read_png(os.path.join(folder, "kneel-%s.png" % sheet))
        if (w, h) != (4 * CELL * SCALE, 4 * CELL * SCALE):
            sys.exit(sheet + ": not a 4x4 sheet of 64x64 cells at 4x")
        for row in range(4):
            for col in range(4):
                sprite, view = SPRITES[row // 2], (row % 2) * 4 + col + 1
                art = []
                for y in range(CELL):
                    line = []
                    for x in range(CELL):
                        r, g, b, a = rows[(row * CELL + y) * SCALE][(col * CELL + x) * SCALE]
                        if a < 128:
                            line.append(-1)
                            continue
                        if (r, g, b) not in index:
                            sys.exit("%s %s view %d: a colour not in PLAYPAL at %d,%d" % (sheet, sprite, view, x, y))
                        line.append(index[(r, g, b)])
                    art.append(line)
                ys = [y for y in range(CELL) if any(v >= 0 for v in art[y])]
                xs = [x for x in range(CELL) if any(art[y][x] >= 0 for y in range(CELL))]
                y0, y1, x0, x1 = ys[0], ys[-1] + 1, xs[0], xs[-1] + 1
                cut = [v for y in range(y0, y1) for v in art[y][x0:x1]]
                data = runs(cut)
                label = "doom_kneel_%s_%s%d" % (sprite.lower(), sheet, view)
                text.append("static const unsigned char %s[] = {" % label)
                for i in range(0, len(data), 40):
                    text.append("    " + ",".join(str(v) for v in data[i:i + 40]) + ",")
                text.append("};")
                # Origin: column MIDDLE, the line under row FEET.
                table[(sprite, sheet, view)] = (label, x1 - x0, y1 - y0, MIDDLE - x0, FEET + 1 - y0)
    text += ["", "struct doom_kneel_frame { const unsigned char *runs; unsigned size; int width, height, left, top; };",
             "struct doom_kneel_art { const char *sprite, *aim; int width, height; unsigned hash; };",
             "static const doom_kneel_art doom_kneel_soldiers[] = {"]
    for sprite in SPRITES:
        w, h, value = patch_hash(wad[sprite + "E1"])
        text.append('    { "%s", "%sE1", %d, %d, 0x%08xu },' % (sprite, sprite, w, h, value))
    text += ["};", "/* [soldier][aim, fire, pain][view 1-8] */",
             "static const doom_kneel_frame doom_kneel_frames[%d][3][8] = {" % len(SPRITES)]
    for sprite in SPRITES:
        text.append("  {")
        for sheet in SHEETS:
            parts = []
            for view in range(1, 9):
                label, w, h, left, top = table[(sprite, sheet, view)]
                parts.append("{ %s, sizeof %s, %d, %d, %d, %d }" % (label, label, w, h, left, top))
            text.append("    { /* %s %s */ " % (sprite, sheet) + ", ".join(parts) + " },")
        text.append("  },")
    text += ["};", "", "#endif", ""]
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "platform", "kneel_frames_stock.h")
    open(out, "w", newline="\n").write("\n".join(text))
    print(out, len(table), "frames")


main()
